import assert from "node:assert/strict";
import { chromium } from "playwright";

const browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto(process.env.FRONTEND_URL ?? "http://127.0.0.1:3000/", { waitUntil: "domcontentloaded" });
  const deck = page.getByRole("region", { name: "Command statistics" });
  await deck.waitFor({ timeout: 60000 });
  assert.equal(await page.locator(".river-monitoring-panel").count(), 0);
  const labels = await deck.locator(".command-stats-tabs button span").allTextContents();
  assert.equal(labels[labels.indexOf("Rivers") + 1], "Monitoring");
  const toggle = deck.getByRole("button", { name: "Monitoring", exact: true });
  assert.equal(await toggle.getAttribute("aria-expanded"), "false");
  await toggle.click();
  const summary = page.getByRole("region", { name: "Monitoring summary" });
  await summary.locator("tbody tr").first().waitFor({ timeout: 60000 });
  assert.equal(await summary.locator("tbody tr").count(), 22);
  assert.equal(await summary.locator("tbody .river-data-source a").count(), 66);
  assert.equal(await summary.evaluate((el) => getComputedStyle(el).color), "rgb(223, 254, 250)");
  await page.screenshot({ path: "monitoring-tab-desktop.png", fullPage: true });
  await summary.getByRole("button", { name: "Hide monitoring" }).click();
  assert.equal(await summary.count(), 0);
  await toggle.click();
  await toggle.click();
  assert.equal(await summary.count(), 0);
  await page.locator(".sidebar nav").getByRole("button", { name: "River Monitoring", exact: true }).click();
  const detailed = page.getByRole("region", { name: "Detailed river monitoring" });
  await detailed.locator("tbody tr").first().waitFor({ timeout: 60000 });
  assert.equal(await detailed.locator("tbody tr").count(), 22);
  assert.equal(await detailed.locator("tbody .river-data-source a").count(), 110);
  await detailed.locator(".monitoring-station-toggle").getByText("Tarbela", { exact: true }).click();
  const inspector = detailed.getByRole("complementary", { name: "River station details" });
  await inspector.getByRole("heading", { name: "Tarbela", exact: true }).waitFor();
  assert.ok(await inspector.locator(".river-data-source a").count() >= 6);
  await page.screenshot({ path: "monitoring-detail-desktop.png", fullPage: true });
  await detailed.locator(".monitoring-station-toggle").getByText("Tarbela", { exact: true }).click();
  assert.equal(await inspector.count(), 0);
  await detailed.getByLabel("Monitoring view river").selectOption("Kabul");
  assert.equal(await detailed.locator("tbody tr").count(), 1);
  await detailed.getByLabel("Monitoring view units").selectOption("cusecs");
  assert.ok((await detailed.locator("tbody tr td").nth(1).innerText()).includes("cusecs"));
  await detailed.getByLabel("Monitoring view river").selectOption("All");
  await detailed.getByLabel("Search monitoring stations").fill("Mangla");
  assert.equal(await detailed.locator("tbody tr").count(), 1);
  await detailed.getByLabel("Search monitoring stations").fill("");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: "monitoring-detail-mobile.png", fullPage: true });
  await page.getByRole("button", { name: "Menu", exact: true }).click();
  await page.locator(".sidebar nav").getByRole("button", { name: "Overview", exact: true }).click();
  await toggle.waitFor({ timeout: 60000 });
  await toggle.click();
  await summary.locator("tbody tr").first().waitFor({ timeout: 60000 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: "monitoring-tab-mobile.png", fullPage: true });
  console.log("Monitoring tab order, show/hide, dark theme, sidebar page, expandable station details, sources, filters, units, and desktop/mobile layouts passed.");
} finally {
  await browser.close();
}
