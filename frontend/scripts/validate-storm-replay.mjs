  await replay.click();
  const root = page.locator(".storm-replay");
  const map = root.locator(".storm-replay-map");
  const slider = page.getByRole("slider", { name: "Storm replay elapsed time", exact: true });
  const peopleBar = page.getByRole("meter", { name: "People in example footprint", exact: true });
  const areaBar = page.getByRole("meter", { name: "Affected area in example footprint", exact: true });
  const checkImpactBars = async (level) => {
    for (const [bar, field] of [[peopleBar, "exposed_population"], [areaBar, "flood_area_km2"]]) {
      const value = source.levels[level][field], maximum = source.levels[5][field];
      assert.equal(Number(await bar.getAttribute("aria-valuenow")), value);
      assert.equal(Number(await bar.getAttribute("aria-valuemax")), maximum);
      const fraction = await bar.evaluate((element) => element.querySelector('.storm-replay-impact-fill').getBoundingClientRect().width / element.clientWidth);
      assert(Math.abs(fraction - value / maximum) < .008, "Visible bar length matches saved value relative to the level-5 example");
    }
  };
  await page.waitForFunction(() => document.querySelector(".storm-replay-map")?.dataset.area === "jhang" && Number(document.querySelector(".storm-replay-map")?.dataset.renderedWater) > 0);
  await page.getByText(/Satellite imagery could not be loaded/).waitFor();
  assert.equal(await root.locator("canvas").count(), 2, "Only the replay map and lightweight current overlay are mounted");
  const source = JSON.parse(await readFile(new URL("../src/data/outlook-exposure/jhang.geojson", import.meta.url), "utf8"));
  await page.getByRole("button", { name: "Jump to peak", exact: true }).click();
  assert.equal(await root.getAttribute("data-level"), "5");
  assert.equal(Number(await root.getAttribute("data-exposed-people")), source.levels[5].exposed_population, "Replay reuses saved exposure totals");
  await checkImpactBars(5);
  await page.getByRole("button", { name: /Lower spread/ }).click();
  assert.equal(await root.getAttribute("data-level"), "2");
  assert.equal(Number(await root.getAttribute("data-exposed-people")), source.levels[2].exposed_population);
  await checkImpactBars(2);
  await page.getByRole("button", { name: /Higher spread/ }).click();
  await page.getByRole("button", { name: "Population", exact: true }).click();
  assert.equal(await map.getAttribute("data-population"), "true");
  await page.getByRole("button", { name: "Population", exact: true }).click();
  const stage = root.locator(".storm-replay-stage");
  await stage.scrollIntoViewIfNeeded();
  await page.getByRole("button", { name: "Draw inspection line", exact: true }).click();
  const box = await map.boundingBox();
  await map.locator("canvas").click({ position: { x: box.width * .33, y: box.height * .47 } });
  await page.getByText("Choose point B on the map · Esc to cancel", { exact: true }).waitFor();
  await map.locator("canvas").click({ position: { x: box.width * .75, y: box.height * .55 } });
  await root.locator(".storm-replay-line-result").waitFor();
  const length = Number(await root.locator(".storm-replay-line-result").getAttribute("data-length-km"));
  const wet = Number(await root.locator(".storm-replay-line-result").getAttribute("data-wet-km"));
  assert(length > 0 && wet >= 0 && wet <= length);
  await root.locator(".storm-replay-layout").screenshot({ path: fileURLToPath(new URL("../screenshots/simulation-storm-replay-inspection.png", import.meta.url)) });
  await slider.fill("0");
  assert.equal(await root.getAttribute("data-level"), "0");
  await checkImpactBars(0);
  assert.equal(await root.locator(".storm-replay-line-result").getAttribute("data-wet-km"), "0");
  await page.waitForFunction(() => document.querySelector(".storm-replay-map").dataset.renderedWater === "0");
  await page.getByRole("button", { name: "Clear inspection line", exact: true }).click();
  await page.getByRole("button", { name: "Play replay", exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector(".storm-replay").dataset.minute) > 3);
  await page.getByRole("button", { name: "Pause replay", exact: true }).click();
  const paused = await root.getAttribute("data-minute");
  await page.waitForTimeout(400);
  assert.equal(await root.getAttribute("data-minute"), paused);
  assert.equal(await peopleBar.locator('.storm-replay-impact-shimmer').evaluate((element) => getComputedStyle(element).animationPlayState), "paused");
  await slider.fill("60");
  await page.getByLabel("Storm replay speed", { exact: true }).selectOption("4");
  const initialFraction = source.levels[1].exposed_population / source.levels[5].exposed_population;
  const nextFraction = source.levels[2].exposed_population / source.levels[5].exposed_population;
  await page.getByRole("button", { name: "Play replay", exact: true }).click();
  await page.waitForFunction(({ initialFraction, nextFraction }) => {
    const meter = document.querySelector('[role="meter"][aria-label="People in example footprint"]');
    if (document.querySelector('.storm-replay').dataset.level !== "2") return false;
    const fraction = meter.querySelector('.storm-replay-impact-fill').getBoundingClientRect().width / meter.clientWidth;
    return fraction > initialFraction + .001 && fraction < nextFraction - .001;
  }, { initialFraction, nextFraction });
  assert.equal(await peopleBar.locator('.storm-replay-impact-shimmer').evaluate((element) => getComputedStyle(element).animationPlayState), "running");
  await page.getByRole("button", { name: "Pause replay", exact: true }).click();
  await checkImpactBars(Number(await root.getAttribute('data-level')));
  await slider.fill("180");
  await page.getByRole("button", { name: "Play replay", exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector(".storm-replay-currents").dataset.phase) > .2 && Number(document.querySelector(".storm-replay-currents").dataset.streaks) > 0);
  await page.getByRole("button", { name: "Pause replay", exact: true }).click();
  const phase = await root.locator(".storm-replay-currents").getAttribute("data-phase");
  await page.waitForTimeout(300);
  assert.equal(await root.locator(".storm-replay-currents").getAttribute("data-phase"), phase, "Pause freezes decorative currents too");
