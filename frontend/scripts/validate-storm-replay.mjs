  await slider.fill("359");
  await page.getByLabel("Storm replay speed", { exact: true }).selectOption("4");
  await page.getByRole("button", { name: "Play replay", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".storm-replay").dataset.minute === "360.00" && document.querySelector(".storm-replay").dataset.playing === "false");
  assert.equal(await root.getAttribute("data-level"), "0");
  await page.getByRole("button", { name: "Restart storm replay", exact: true }).click();
  assert.equal(await slider.inputValue(), "0");
  await page.getByLabel("Storm replay district", { exact: true }).selectOption("badin");
  await page.getByText(/Badin: population context is available/).waitFor();
  assert.equal(await slider.isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "Play replay", exact: true }).isDisabled(), true);
  assert.equal(await root.getAttribute("data-exposed-people"), "", "No invented Badin exposure");
  assert.equal(await root.getByRole('meter').count(), 0, "Missing footprint data cannot show a misleading zero-exposure meter");
  assert.equal(await page.getByTestId('replay-exposed-population').innerText(), 'Unavailable');
  await page.getByLabel("Storm replay district", { exact: true }).selectOption("lahore");
  await page.waitForFunction(() => document.querySelector(".storm-replay-map").dataset.area === "lahore");
  await slider.fill("198");
  await page.getByRole("button", { name: "Whole district", exact: true }).click();
  await page.waitForTimeout(1100);
  const regionZoom = Number(await map.getAttribute("data-zoom"));
  await page.getByRole("button", { name: "River close-up", exact: true }).click();
  await page.waitForFunction((zoom) => Number(document.querySelector(".storm-replay-map").dataset.zoom) > zoom + .3, regionZoom);
  await page.waitForTimeout(1600);
  await root.locator(".storm-replay-layout").screenshot({ path: fileURLToPath(new URL("../screenshots/simulation-storm-replay.png", import.meta.url)) });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.getByText(/Your browser prefers reduced motion/).waitFor();
  assert.equal(await peopleBar.locator('.storm-replay-impact-shimmer').evaluate((element) => getComputedStyle(element).animationName), "none");
  assert.equal(await page.getByRole("button", { name: "Play replay", exact: true }).isDisabled(), true);
  await slider.fill("0");
  assert.equal(await root.getAttribute("data-level"), "0");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.getByRole("button", { name: "Play replay", exact: true }).click();
  await page.evaluate(() => { Object.defineProperty(document, "hidden", { configurable: true, value: true }); document.dispatchEvent(new Event("visibilitychange")); });
  await page.waitForFunction(() => document.querySelector(".storm-replay").dataset.playing === "false");
  const hidden = await slider.inputValue();
  await page.waitForTimeout(300);
  assert.equal(await slider.inputValue(), hidden);
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event("visibilitychange")); });
  await stage.scrollIntoViewIfNeeded();
  await page.getByRole("button", { name: "Play replay", exact: true }).click();
  await page.locator(".storm-replay-method").evaluate((element) => element.scrollIntoView({ block: "start" }));
  await page.waitForFunction(() => document.querySelector(".storm-replay").dataset.playing === "false");
  await page.locator(".storm-replay-method summary").click();
  assert.match(await page.locator(".storm-replay-method").innerText(), /512 midpoint samples/);
  await page.setViewportSize({ width: 1024, height: 850 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await root.locator(".storm-replay-layout").screenshot({ path: fileURLToPath(new URL("../screenshots/simulation-storm-replay-compact.png", import.meta.url)) });
