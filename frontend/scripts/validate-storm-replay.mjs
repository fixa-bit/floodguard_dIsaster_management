  assert.equal(await page.locator(".storm-replay canvas").count(), 0, "Leaving replay releases its map and current canvas");
  assert.equal(await page.getByRole("slider", { name: "Reading 1 value", exact: true }).inputValue(), "314000", "Monitoring draft survives replay");
